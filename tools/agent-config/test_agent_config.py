    def global_setup(self, size=100):
        (self.home / ".claude" / "tools" / "agent-config").mkdir(parents=True)
        (self.home / ".codex").mkdir()
        (self.home / ".claude" / "CLAUDE.md").write_text("# Global\n\n" + "y" * size + "\n", encoding="utf-8")

    # 24
    def test_global_writes_codex_agents_md(self):
        self.global_setup()
        r = self.run_tool("--global")
        self.assertEqual(r.returncode, 0, r.stderr)
        out = self.home / ".codex" / "AGENTS.md"
        first = out.read_text(encoding="utf-8").split("\n")[0]
        self.assertTrue(first.startswith(MARKER))
        self.assertIn("~/.claude/CLAUDE.md", first)
        self.assertEqual(self.run_tool("--global", "--check").returncode, 0)
        (self.home / ".claude" / "CLAUDE.md").write_text("# Global\n\n" + "y" * 40000 + "\n", encoding="utf-8")
        self.assertEqual(self.run_tool("--global").returncode, 0)

    # 25
    def test_global_skill_links_live_in_home_agents(self):
        self.global_setup()
        d = self.home / ".claude" / "skills" / "demo"
        d.mkdir(parents=True)
        (d / "SKILL.md").write_text("---\ndescription: d\n---\nb\n", encoding="utf-8")
        (self.home / ".claude" / "tools" / "agent-config" / "global.json").write_text(
            json.dumps({"skills": ["demo"]}), encoding="utf-8")
        r = self.run_tool("--global")
        self.assertEqual(r.returncode, 0, r.stderr)
        link = self.home / ".agents" / "skills" / "demo"
        self.assertEqual(os.readlink(link), LINK + "demo")
        self.assertTrue((link / "SKILL.md").is_file())

    # 26
    def test_global_refuses_missing_codex_dir_and_foreign_codex_home(self):
        with self.subTest("no .codex"):
            (self.home / ".claude").mkdir()
            (self.home / ".claude" / "CLAUDE.md").write_text("# G\n", encoding="utf-8")
            self.assertEqual(self.run_tool("--global").returncode, 2)
        (self.home / ".codex").mkdir()
        with self.subTest("foreign CODEX_HOME"):
            other = self.tmp / "other"
            other.mkdir()
            r = self.run_tool("--global", env_extra={"CODEX_HOME": str(other)})
            self.assertEqual(r.returncode, 2)
            self.assertFalse((self.home / ".codex" / "AGENTS.md").exists())
        with self.subTest("CODEX_HOME is ~/.codex"):
            r = self.run_tool("--global", env_extra={"CODEX_HOME": str(self.home / ".codex")})
            self.assertEqual(r.returncode, 0, r.stderr)

    # 27
    def test_cli_requires_exactly_one_profile(self):
        self.assertEqual(self.run_tool().returncode, 2)
        self.assertEqual(self.run_tool("--root", str(self.repo), "--global").returncode, 2)

    # 28
    def test_output_independent_of_cwd(self):
        self.assertEqual(self.run_tool("--root", str(self.repo), cwd="/").returncode, 0)
        a = self.agents.read_bytes()
        self.agents.unlink()
        self.assertEqual(self.run_tool("--root", str(self.repo), cwd=str(self.repo)).returncode, 0)
        self.assertEqual(self.agents.read_bytes(), a)


