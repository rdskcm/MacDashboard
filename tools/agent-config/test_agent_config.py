    # 20
    def test_symlinked_output_dir_refused(self):
        for label in (".agents", ".agents/skills"):
            with self.subTest(label):
                outside = self.tmp / "outside"
                outside.mkdir()
                agents_dir = self.repo / ".agents"
                if label == ".agents":
                    agents_dir.symlink_to(outside)
                else:
                    agents_dir.mkdir()
                    (agents_dir / "skills").symlink_to(outside)
                r = self.root()
                self.assertEqual(r.returncode, 2)
                self.assertEqual(list(outside.iterdir()), [])
                self.assertFalse(self.agents.exists())
                if label == ".agents":
                    agents_dir.unlink()
                else:
                    (agents_dir / "skills").unlink()
                    agents_dir.rmdir()
                outside.rmdir()

