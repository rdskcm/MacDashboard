#!/usr/bin/env python3
"""Generate Codex-readable AGENTS.md files and skill links from a Claude Code setup.

Purpose: keep `AGENTS.md` (read by Codex and other agent harnesses) in sync with
`CLAUDE.md` (read by Claude Code), rewriting every sentence that claims "a hook
enforces this rule" so that it is true outside Claude Code, and linking skills.

Usage:
    python3 -I agent_config.py --root DIR [--check]
    python3 -I agent_config.py --global [--check]

Exit codes:
    0  up to date (or written)
    1  drift (--check only)
    2  invalid source or config, refusal, or usage error

Method ported from StatGlass scripts/agent-config
(https://github.com/steamfield/statglass, Apache-2.0), itself adapted from
OpenData's sync.py. No code was copied.
"""

import argparse
import json
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, List, Optional, Tuple

MARKER_PREFIX = "<!-- GENERATED by agent_config.py"
LINK_PREFIX = "../../.claude/skills/"
SKILL_NAME = r"[A-Za-z0-9_][A-Za-z0-9_.-]*"
PROJECT_DOC_MAX_BYTES = 32768

_GUARD_WORD = re.compile(r"\b[a-z0-9]+(?:-[a-z0-9]+)*-guard(?:\.sh)?\b")
_HOOK_WORD = re.compile(r"\bhooks?\b")
_ENFORCE_WORD = re.compile(r"\b(?:refus|block|den|reject|enforc)\w*")

APPENDIX = """---

## Under Codex or another agent harness

This file is generated from {label} by agent_config.py. Do not edit it: edit {label}, then rerun the generator.

The source was written for Claude Code. Claude Code's hooks, permission rules and settings do not run under Codex or any other harness, so no rule in this file is enforced mechanically here. Treat every rule above as an instruction that you apply yourself. Where the source says that a Claude Code hook enforces a rule, the text above has been rewritten to say that the rule is not enforced here.
"""


class ConfigError(Exception):
    """Any validation failure; main() maps it to exit 2."""


@dataclass
class Profile:
    label: str
    source: Path
    config: Path
    out_doc: Path
    skills_src: Path
    skills_out: Path
    no_symlink_dirs: List[Path]
    size_cap: Optional[int]
    display: Callable[[Path], str]


def marker_line(label: str) -> str:
    return f"{MARKER_PREFIX} from {label}. Do not edit: edit {label}, then rerun the generator. -->"


def project_profile(root) -> Profile:
    root = Path(root).resolve()
    if not root.is_dir():
        raise ConfigError(f"--root {root} is not a directory")

    def display(p: Path) -> str:
        try:
            return str(p.relative_to(root))
        except ValueError:
            return str(p)

    return Profile(
        label="CLAUDE.md",
        source=root / "CLAUDE.md",
        config=root / ".claude" / "agent-config.json",
        out_doc=root / "AGENTS.md",
        skills_src=root / ".claude" / "skills",
        skills_out=root / ".agents" / "skills",
        no_symlink_dirs=[root / ".agents", root / ".agents" / "skills"],
        size_cap=PROJECT_DOC_MAX_BYTES,
        display=display,
    )


def global_profile() -> Profile:
    home = Path.home()
    codex_env = os.environ.get("CODEX_HOME", "")
    if codex_env and Path(codex_env).expanduser().resolve() != (home / ".codex").resolve():
        raise ConfigError(f"CODEX_HOME={codex_env} is not ~/.codex; refusing to write ~/.codex while Codex reads elsewhere")
    codex = home / ".codex"
    if codex.is_symlink() or not codex.is_dir():
        raise ConfigError("~/.codex not found: Codex is not installed for this user")

    def display(p: Path) -> str:
        try:
            return "~/" + str(p.relative_to(home))
        except ValueError:
            return str(p)

    return Profile(
        label="~/.claude/CLAUDE.md",
        source=home / ".claude" / "CLAUDE.md",
        config=home / ".claude" / "tools" / "agent-config" / "global.json",
        out_doc=home / ".codex" / "AGENTS.md",
        skills_src=home / ".claude" / "skills",
        skills_out=home / ".agents" / "skills",
        no_symlink_dirs=[home / ".codex", home / ".agents", home / ".agents" / "skills"],
        size_cap=None,
        display=display,
    )


def load_config(path: Path) -> Tuple[List[Tuple[str, str]], List[str]]:
    if not os.path.lexists(path):
        return [], []
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ConfigError(f"{path}: malformed JSON: {e}")
    if not isinstance(data, dict):
        raise ConfigError(f"{path}: top level must be a JSON object")
    for key in data:
        if key not in ("rewrites", "skills"):
            raise ConfigError(f"{path}: unknown key {key!r}")
    rewrites: List[Tuple[str, str]] = []
    raw = data.get("rewrites", [])
    if not isinstance(raw, list):
        raise ConfigError(f"{path}: 'rewrites' must be a list")
    for i, item in enumerate(raw):
        if not isinstance(item, dict) or set(item) != {"find", "replace"}:
            raise ConfigError(f"{path}: rewrites[{i}] must be an object with exactly the keys 'find' and 'replace'")
        if not isinstance(item["find"], str) or not item["find"]:
            raise ConfigError(f"{path}: rewrites[{i}].find must be a non-empty string")
        if not isinstance(item["replace"], str):
            raise ConfigError(f"{path}: rewrites[{i}].replace must be a string")
        rewrites.append((item["find"], item["replace"]))
    skills = data.get("skills", [])
    if not isinstance(skills, list):
        raise ConfigError(f"{path}: 'skills' must be a list")
    seen = set()
    for i, name in enumerate(skills):
        if not isinstance(name, str) or not re.fullmatch(SKILL_NAME, name):
            raise ConfigError(f"{path}: skills[{i}] is not a valid skill name")
        if name in seen:
            raise ConfigError(f"{path}: skills[{i}] duplicates {name!r}")
        seen.add(name)
    return rewrites, list(skills)


def is_claim(line: str) -> bool:
    low = line.lower()
    if ".claude/hooks/" in low or "pretooluse" in low:
        return True
    if _GUARD_WORD.search(low):
        return True
    return bool(_HOOK_WORD.search(low) and _ENFORCE_WORD.search(low))


def render(profile: Profile, rewrites: List[Tuple[str, str]]) -> str:
    try:
        text = profile.source.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise ConfigError(f"source {profile.display(profile.source)} not found")
    spans = []
    for i, (find, _replace) in enumerate(rewrites):
        n = text.count(find)
        if n != 1:
            raise ConfigError(
                f"rewrite {i} in {profile.config}: its find text occurs {n} times in {profile.label}; "
                "the source changed, update the rewrite"
            )
        start = text.index(find)
        spans.append((start, start + len(find), i))
    spans.sort()
    for a, b in zip(spans, spans[1:]):
        if b[0] < a[1]:
            raise ConfigError(f"rewrites {a[2]} and {b[2]} in {profile.config} overlap in {profile.label}")
    swept = text
    for start, end, _i in reversed(spans):
        swept = swept[:start] + "\n" * text.count("\n", start, end) + swept[end:]
    for n, line in enumerate(swept.split("\n"), 1):
        if is_claim(line):
            raise ConfigError(
                f"{profile.label} line {n} says a Claude Code hook enforces a rule, which is false under Codex; "
                f"add a rewrite for it to {profile.config}"
            )
    body = text
    for start, end, i in reversed(spans):
        body = body[:start] + rewrites[i][1] + body[end:]
    return marker_line(profile.label) + "\n\n" + body.rstrip("\n") + "\n\n" + APPENDIX.format(label=profile.label)


_BLOCK_INDICATORS = (">", "|", ">-", "|-", ">+", "|+")


def check_skill(profile: Profile, name: str) -> None:
    err = ConfigError(f"skill {name}: SKILL.md needs YAML frontmatter with a non-empty description")
    path = profile.skills_src / name / "SKILL.md"
    try:
        lines = path.read_text(encoding="utf-8").split("\n")
    except (OSError, UnicodeError):
        raise err
    if not lines or lines[0].rstrip() != "---":
        raise err
    end = None
    for j in range(1, len(lines)):
        if lines[j].rstrip() == "---":
            end = j
            break
    if end is None:
        raise err
    front = lines[1:end]
    for j, line in enumerate(front):
        m = re.match(r"description:(.*)$", line)
        if not m:
            continue
        value = m.group(1).strip()
        if not value:
            raise err
        if value in _BLOCK_INDICATORS:
            nxt = front[j + 1] if j + 1 < len(front) else ""
            if not (nxt[:1] in (" ", "\t") and nxt.strip()):
                raise err
        return
    raise err


def _is_managed_link(p: Path) -> bool:
    if not p.is_symlink():
        return False
    return re.fullmatch(re.escape(LINK_PREFIX) + SKILL_NAME, os.readlink(p)) is not None


def plan(profile: Profile):
    """Return (actions, notes, desired). Performs no writes."""
    for d in profile.no_symlink_dirs:
        if d.is_symlink():
            raise ConfigError(f"refusing to write through symlinked {profile.display(d)}")
    override = profile.out_doc.with_name("AGENTS.override.md")
    if os.path.lexists(override):
        raise ConfigError(f"{profile.display(override)} exists and would shadow the generated file; move it away first")
    rewrites, skills = load_config(profile.config)
    desired = render(profile, rewrites)
    nbytes = len(desired.encode())
    if profile.size_cap and nbytes >= profile.size_cap:
        raise ConfigError(f"generated {profile.display(profile.out_doc)} is {nbytes} bytes, at or over the {profile.size_cap} byte cap")

    actions = []
    notes = []
    out = profile.out_doc
    if os.path.lexists(out):
        managed = False
        if out.is_file() and not out.is_symlink():
            try:
                with open(out, "rb") as f:
                    managed = f.readline().decode("utf-8").startswith(MARKER_PREFIX)
            except (OSError, UnicodeError):
                managed = False
        if not managed:
            raise ConfigError(f"refusing to overwrite hand-written {profile.display(out)}; move it away first")
        if out.read_bytes() != desired.encode():
            actions.append(("write", out))
    else:
        actions.append(("write", out))

    for name in skills:
        check_skill(profile, name)
    out_dir = profile.skills_out
    if os.path.lexists(out_dir) and not out_dir.is_dir():
        raise ConfigError(f"{profile.display(out_dir)} exists and is not a directory")
    listed = set(skills)
    existing = {}
    if out_dir.is_dir():
        for entry in sorted(out_dir.iterdir(), key=lambda p: p.name):
            if entry.name.startswith("."):
                continue
            existing[entry.name] = entry
    for name, entry in existing.items():
        managed = _is_managed_link(entry)
        if name in listed:
            if not managed:
                raise ConfigError(f"unmanaged entry {profile.display(entry)} is at a listed skill name; move it away first")
            if os.readlink(entry) != LINK_PREFIX + name:
                actions.append(("relink", entry))
        elif managed:
            actions.append(("remove", entry))
        else:
            notes.append(f"leaving unmanaged {profile.display(entry)}")
    for name in skills:
        if name not in existing:
            actions.append(("link", out_dir / name))
    return actions, notes, desired


def apply(profile: Profile, actions, desired: str) -> None:
    for kind, path in actions:
        if kind == "write":
            fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".agents-md-", suffix=".tmp")
            try:
                with os.fdopen(fd, "wb") as f:
                    f.write(desired.encode())
                os.chmod(tmp, 0o644)
                os.replace(tmp, path)
            except BaseException:
                if os.path.lexists(tmp):
                    os.unlink(tmp)
                raise
        elif kind == "link":
            profile.skills_out.mkdir(parents=True, exist_ok=True)
            os.symlink(LINK_PREFIX + path.name, path)
        elif kind == "relink":
            os.unlink(path)
            os.symlink(LINK_PREFIX + path.name, path)
        elif kind == "remove":
            os.unlink(path)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="agent_config.py", description="Generate AGENTS.md and skill links from CLAUDE.md.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--root", metavar="DIR", help="project root holding CLAUDE.md")
    group.add_argument("--global", dest="global_", action="store_true", help="generate ~/.codex/AGENTS.md from ~/.claude/CLAUDE.md")
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    try:
        args = parser.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    try:
        profile = global_profile() if args.global_ else project_profile(args.root)
        where = "~/.codex" if args.global_ else profile.source.parent.name
        actions, notes, desired = plan(profile)
        for note in notes:
            print(note, file=sys.stderr)
        if args.check:
            if actions:
                print(f"agent-config: stale ({where}):", file=sys.stderr)
                for kind, path in actions:
                    print(f"  {kind} {profile.display(path)}", file=sys.stderr)
                print("  run the same command without --check", file=sys.stderr)
                return 1
            print(f"agent-config: up to date ({where})")
            return 0
        apply(profile, actions, desired)
        if actions:
            for kind, path in actions:
                print(f"{kind} {profile.display(path)}")
        else:
            print("up to date")
        return 0
    except (ConfigError, OSError, UnicodeError) as e:
        print(f"agent-config: error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
